# Shared helpers for repo scripts. Source, don't execute.
# shellcheck shell=bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RUN_DIR="$ROOT/.run"
MODELS_DIR="${FT_MODELS_DIR:-$HOME/.cache/feedback-tool/models}"
WHISPER_MODEL="${WHISPER_MODEL:-large-v3-turbo}"
ANCHOR_MODEL_DEFAULT="qwen3:14b"
mkdir -p "$RUN_DIR"

if [ -x /opt/homebrew/bin/brew ]; then eval "$(/opt/homebrew/bin/brew shellenv)"; fi
export PATH="/opt/homebrew/opt/node@22/bin:$PATH"

c_ok() { printf '  \033[32m✓\033[0m %s\n' "$*"; }
c_do() { printf '  \033[34m→\033[0m %s\n' "$*"; }
c_warn() { printf '  \033[33m!\033[0m %s\n' "$*"; }
c_err() { printf '  \033[31m✗\033[0m %s\n' "$*" >&2; }

docker_running() { docker info >/dev/null 2>&1; }

supabase_running() { (cd "$ROOT" && supabase status >/dev/null 2>&1); }

ensure_supabase() {
  if ! docker_running; then
    c_err "Docker isn't running. Open Docker Desktop (open -a Docker), wait for the whale icon to settle, then retry."
    return 1
  fi
  if supabase_running; then c_ok "Supabase running"; else
    c_do "Starting Supabase (first run downloads images; can take a few minutes)…"
    (cd "$ROOT" && supabase start >"$RUN_DIR/supabase-start.log" 2>&1) || {
      c_err "supabase start failed — see .run/supabase-start.log"; return 1; }
    c_ok "Supabase started"
  fi
}

# Read a value from `supabase status -o env`.
sb_env() {
  (cd "$ROOT" && supabase status -o env 2>/dev/null) | grep "^$1=" | head -1 | cut -d= -f2- | tr -d '"'
}

# Stable per-machine secret for HMAC proxy tokens (never committed).
proxy_secret() {
  local f="$RUN_DIR/proxy-token-secret"
  if [ ! -s "$f" ]; then openssl rand -hex 32 >"$f"; chmod 600 "$f"; fi
  cat "$f"
}

# Write apps/web/.env.local and apps/proxy/.dev.vars for local dev.
write_env_files() {
  local app_origin="${1:-http://localhost:3000}" proxy_origin="${2:-http://localhost:8787}"
  local secret anchor_model
  secret="$(proxy_secret)"
  anchor_model="$(cat "$RUN_DIR/anchor-model" 2>/dev/null || echo "$ANCHOR_MODEL_DEFAULT")"
  cat >"$ROOT/apps/web/.env.local" <<EOF
# Generated by scripts/lib.sh — do not commit.
SUPABASE_URL=$(sb_env API_URL)
SUPABASE_ANON_KEY=$(sb_env ANON_KEY)
SUPABASE_SERVICE_ROLE_KEY=$(sb_env SERVICE_ROLE_KEY)
MAILPIT_URL=$(sb_env MAILPIT_URL)
APP_ORIGIN=$app_origin
PROXY_ORIGIN=$proxy_origin
PROXY_TOKEN_SECRET=$secret
TRANSCRIBER=local
ANCHOR_RESOLVER=local
SCREENSHOT=local
MAILER=local
PROXY_HOST=local
WHISPER_URL=http://127.0.0.1:8178
OLLAMA_URL=http://127.0.0.1:11434
ANCHOR_MODEL=$anchor_model
EOF
  cat >"$ROOT/apps/proxy/.dev.vars" <<EOF
PROXY_TOKEN_SECRET=$secret
ALLOWED_APP_ORIGINS=$app_origin
APP_ORIGIN=$app_origin
ENVIRONMENT=development
EOF
}

port_in_use() { lsof -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1; }

wait_for_url() {
  local url="$1" tries="${2:-60}"
  for _ in $(seq "$tries"); do
    if curl -sf -o /dev/null "$url"; then return 0; fi
    sleep 1
  done
  return 1
}
